export function pickQuoteForDay(dateKey: string): Quote {
  let hash = 0;
  for (let i = 0; i < dateKey.length; i++) {
    hash = (hash * 31 + dateKey.charCodeAt(i)) >>> 0;
  }
  return quotes[hash % quotes.length]!;
}
